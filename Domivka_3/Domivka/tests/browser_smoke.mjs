import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
for(let n=0;;n++){try{const r=await fetch('http://127.0.0.1:8765/api/version');if(r.ok)break}catch{}if(n>60)throw Error('Fixture did not start');await new Promise(r=>setTimeout(r,500))}
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
await page.getByRole('tab',{name:'Маркет',exact:true}).click();
await page.locator('.mk-name').first().waitFor();
assert.equal(await page.locator('.mk-name').count(),2);
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'No horizontal page overflow');
await mkdir('test-results',{recursive:true});
await page.screenshot({path:'test-results/market-light.png',fullPage:true});
await page.locator('.mk-name').first().click();
await page.locator('#mk-buy').click();
await page.locator('#mo-carrier').selectOption('pickup');
await page.locator('#mo-name').fill('Тестовий Покупець');
await page.locator('#mo-phone').fill('+380501234567');
await page.locator('#sheets input[type=checkbox]').last().check();
const [response]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/market/orders')&&r.request().method()==='POST'),page.locator('#mo-submit').click()]);
assert.equal(response.status(),200,await response.text());
const placed=await response.json();assert.ok(placed.item.id);assert.equal(placed.item.payment,'pickup');
await page.screenshot({path:'test-results/order-confirmed.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
await page.locator('[data-biz=hub]').click();
await page.locator('[data-biz=club]').first().waitFor({timeout:10000});
await page.screenshot({path:'test-results/daily-hub.png',fullPage:true});
assert.deepEqual(errors,[],'No uncaught browser JavaScript errors');
await browser.close();console.log('Browser: market, pickup order, daily hub, responsive layout passed');
